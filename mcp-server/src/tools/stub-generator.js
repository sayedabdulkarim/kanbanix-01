import path from 'path';

/**
 * Multi-language stub file generator
 * Generates appropriate stub content for any file type
 */
export class StubGenerator {
  /**
   * Generate appropriate stub content based on file path and language
   */
  static generateStub(filePath, language = null) {
    const ext = path.extname(filePath).toLowerCase();
    const basename = path.basename(filePath, ext);
    
    // Handle by extension first
    switch (ext) {
      // Web technologies
      case '.html':
        return `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${basename}</title>
</head>
<body>
    <h1>${basename}</h1>
</body>
</html>`;
      
      case '.css':
      case '.scss':
      case '.sass':
      case '.less':
        return `/* Auto-generated stylesheet: ${basename} */
* {
  box-sizing: border-box;
}

body {
  margin: 0;
  padding: 0;
}`;
      
      // JavaScript/TypeScript
      case '.js':
      case '.mjs':
        return `// Auto-generated JavaScript file: ${basename}

export default {
  // Add your code here
};`;
      
      case '.jsx':
        return `// Auto-generated React component: ${basename}
import React from 'react';

export default function ${basename}() {
  return (
    <div>
      <h1>${basename}</h1>
    </div>
  );
}`;
      
      case '.ts':
        // Special handling for common utility files
        if (basename.toLowerCase() === 'prisma' && filePath.includes('lib')) {
          return `import { PrismaClient } from '@prisma/client';

const globalForPrisma = global as unknown as { prisma: PrismaClient };

export const prisma =
  globalForPrisma.prisma ||
  new PrismaClient({
    log: process.env.NODE_ENV === 'development' ? ['query', 'error', 'warn'] : ['error'],
  });

if (process.env.NODE_ENV !== 'production') globalForPrisma.prisma = prisma;`;
        }
        
        // Default TypeScript stub
        return `// Auto-generated TypeScript file: ${basename}

export interface ${basename}Interface {
  // Add interface properties here
}

export default class ${basename} {
  // Add your code here
}`;
      
      case '.tsx':
        return `// Auto-generated React TypeScript component: ${basename}
import React from 'react';

interface ${basename}Props {
  // Add props here
}

const ${basename}: React.FC<${basename}Props> = (props) => {
  return (
    <div>
      <h1>${basename}</h1>
    </div>
  );
};

export default ${basename};`;
      
      // Python
      case '.py':
        return `#!/usr/bin/env python3
"""
Auto-generated Python module: ${basename}
"""

def main():
    """Main function"""
    pass

if __name__ == "__main__":
    main()`;
      
      // Java
      case '.java':
        const className = basename.charAt(0).toUpperCase() + basename.slice(1);
        return `// Auto-generated Java class: ${className}

public class ${className} {
    public static void main(String[] args) {
        System.out.println("${className} class");
    }
}`;
      
      // Go
      case '.go':
        const packageName = path.dirname(filePath).split('/').pop() || 'main';
        return `// Auto-generated Go file: ${basename}
package ${packageName}

import "fmt"

func main() {
    fmt.Println("${basename}")
}`;
      
      // Rust
      case '.rs':
        return `// Auto-generated Rust file: ${basename}

fn main() {
    println!("${basename}");
}`;
      
      // Ruby
      case '.rb':
        return `#!/usr/bin/env ruby
# Auto-generated Ruby file: ${basename}

class ${basename.charAt(0).toUpperCase() + basename.slice(1)}
  def initialize
    # Constructor
  end
end`;
      
      // PHP
      case '.php':
        return `<?php
/**
 * Auto-generated PHP file: ${basename}
 */

class ${basename.charAt(0).toUpperCase() + basename.slice(1)} {
    public function __construct() {
        // Constructor
    }
}
?>`;
      
      // C#
      case '.cs':
        return `// Auto-generated C# file: ${basename}
using System;

namespace AutoGenerated
{
    public class ${basename.charAt(0).toUpperCase() + basename.slice(1)}
    {
        static void Main(string[] args)
        {
            Console.WriteLine("${basename}");
        }
    }
}`;
      
      // C/C++
      case '.c':
        return `/* Auto-generated C file: ${basename} */
#include <stdio.h>

int main() {
    printf("${basename}\\n");
    return 0;
}`;
      
      case '.cpp':
      case '.cc':
        return `// Auto-generated C++ file: ${basename}
#include <iostream>

int main() {
    std::cout << "${basename}" << std::endl;
    return 0;
}`;
      
      case '.h':
      case '.hpp':
        const guard = `${basename.toUpperCase()}_H`;
        return `#ifndef ${guard}
#define ${guard}

// Auto-generated header file: ${basename}

#endif // ${guard}`;
      
      // Swift
      case '.swift':
        return `// Auto-generated Swift file: ${basename}
import Foundation

class ${basename.charAt(0).toUpperCase() + basename.slice(1)} {
    init() {
        // Constructor
    }
}`;
      
      // Kotlin
      case '.kt':
        return `// Auto-generated Kotlin file: ${basename}
fun main() {
    println("${basename}")
}`;
      
      // Scala
      case '.scala':
        return `// Auto-generated Scala file: ${basename}
object ${basename.charAt(0).toUpperCase() + basename.slice(1)} {
  def main(args: Array[String]): Unit = {
    println("${basename}")
  }
}`;
      
      // Shell scripts
      case '.sh':
      case '.bash':
        return `#!/bin/bash
# Auto-generated shell script: ${basename}

echo "${basename}"`;
      
      // YAML
      case '.yml':
      case '.yaml':
        return `# Auto-generated YAML file: ${basename}
name: ${basename}
version: 1.0.0`;
      
      // JSON
      case '.json':
        return JSON.stringify({
          name: basename,
          version: "1.0.0",
          description: `Auto-generated ${basename}`
        }, null, 2);
      
      // XML
      case '.xml':
        return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Auto-generated XML file: ${basename} -->
<root>
  <name>${basename}</name>
</root>`;
      
      // Markdown
      case '.md':
        return `# ${basename}

Auto-generated markdown file.`;
      
      // Configuration files
      case '.env':
        return `# Auto-generated environment file
# Add your environment variables here
`;
      
      case '.gitignore':
        return `# Auto-generated gitignore
node_modules/
*.log
.env
`;
      
      // Default for unknown extensions
      default:
        // Try to infer from language parameter
        if (language) {
          switch (language.toLowerCase()) {
            case 'python':
              return `# Auto-generated Python file: ${basename}\n`;
            case 'javascript':
            case 'typescript':
              return `// Auto-generated file: ${basename}\n`;
            case 'java':
            case 'kotlin':
            case 'scala':
              return `// Auto-generated file: ${basename}\n`;
            case 'go':
              return `// Auto-generated Go file: ${basename}\npackage main\n`;
            case 'rust':
              return `// Auto-generated Rust file: ${basename}\n`;
            case 'ruby':
              return `# Auto-generated Ruby file: ${basename}\n`;
            case 'php':
              return `<?php\n// Auto-generated PHP file: ${basename}\n?>`;
            default:
              return `Auto-generated file: ${basename}\n`;
          }
        }
        return `Auto-generated file: ${basename}\n`;
    }
  }
  
  /**
   * Detect the appropriate file to create based on error message
   */
  static detectFileFromError(errorMessage, projectLanguage = null) {
    // Extract file paths from error messages
    const patterns = [
      /Module not found: Can't resolve ['"]([^'"]+)['"]/i, // Most specific Next.js pattern
      /Cannot (?:find|resolve) ['"]([^'"]+)['"]/i,
      /Module not found: .*['"]([^'"]+)['"]/i,
      /Could not (?:find|locate) file ['"]([^'"]+)['"]/i,
      /No such file or directory.*['"]([^'"]+)['"]/i,
      /cannot open ['"]([^'"]+)['"]/i,
      /File ['"]([^'"]+)['"] not found/i,
      /'([^']+)' (?:not found|does not exist)/i,
    ];
    
    for (const pattern of patterns) {
      const match = errorMessage.match(pattern);
      if (match && match[1]) {
        let filePath = match[1];
        
        // Handle various import path formats
        if (filePath.startsWith('@/')) {
          // In Next.js, @/ maps to src/ if src directory exists, otherwise root
          // This will be resolved correctly when joined with workspace path
          filePath = filePath.replace('@/', 'src/');
        } else if (filePath.startsWith('~')) {
          // Another common alias
          filePath = filePath.replace('~/', '');
        } else if (filePath.startsWith('@')) {
          // Handle other @ aliases (like @components, @utils)
          // Remove @ and treat as relative to root
          filePath = filePath.substring(1);
          if (filePath.startsWith('/')) {
            filePath = filePath.substring(1);
          }
        }
        
        // Add extension if missing (based on language)
        if (!path.extname(filePath)) {
          const ext = StubGenerator.getDefaultExtension(projectLanguage);
          if (ext) {
            filePath += ext;
          }
        }
        
        return filePath;
      }
    }
    
    return null;
  }
  
  /**
   * Get default file extension for a language
   */
  static getDefaultExtension(language) {
    const extensionMap = {
      'javascript': '.js',
      'typescript': '.ts',
      'python': '.py',
      'java': '.java',
      'go': '.go',
      'rust': '.rs',
      'ruby': '.rb',
      'php': '.php',
      'csharp': '.cs',
      'c': '.c',
      'cpp': '.cpp',
      'swift': '.swift',
      'kotlin': '.kt',
      'scala': '.scala'
    };
    
    return extensionMap[language?.toLowerCase()] || '';
  }
}

export default StubGenerator;